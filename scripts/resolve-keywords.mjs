// Resolves the theme lists' TMDB keyword ids (exact name matches only) and
// writes src/discover/keywords.ts. Prints how many titles each keyword has so
// a wrong or empty keyword is visible.
//   node scripts/resolve-keywords.mjs
import { writeFileSync } from "node:fs";
import { connect, norm } from "./tmdb-cdp.mjs";

const THEMES = {
  mafia: ["mafia", "organized crime", "mobster", "gangster"],
  heist: ["heist", "bank robbery"],
  timeTravel: ["time travel", "time loop"],
  space: ["outer space", "space travel", "space opera"],
  dystopia: ["dystopia"],
  superhero: ["superhero", "superhero team"],
  spy: ["spy", "espionage", "secret agent"],
  courtroom: ["courtroom", "courtroom drama", "legal thriller"],
  trueStory: ["based on true story"],
  comingOfAge: ["coming of age"],
  serialKiller: ["serial killer"],
  zombie: ["zombie", "zombie apocalypse"],
  martialArts: ["martial arts", "kung fu"],
  sport: ["sport", "sports", "boxing"],
  roadTrip: ["road trip", "road movie"],
  revenge: ["revenge"],
  postApocalyptic: ["post-apocalyptic future", "post-apocalyptic", "apocalypse"],
  cyberpunk: ["cyberpunk"],
};

const { tmdb, close } = await connect();
const out = {};
for (const [theme, queries] of Object.entries(THEMES)) {
  const ids = [];
  for (const q of queries) {
    const res = await tmdb("/search/keyword", { query: q });
    const hit = (res.results ?? []).find((k) => norm(k.name) === norm(q));
    if (!hit) {
      console.log(`  ${theme}: no exact keyword for "${q}"`);
      continue;
    }
    const m = await tmdb("/discover/movie", { with_keywords: hit.id });
    const t = await tmdb("/discover/tv", { with_keywords: hit.id });
    console.log(`  ${theme}: "${hit.name}" = ${hit.id} (${m.total_results} movies, ${t.total_results} series)`);
    if (m.total_results + t.total_results >= 20) ids.push(hit.id);
  }
  if (!ids.length) throw new Error(`No usable keyword for ${theme}`);
  out[theme] = [...new Set(ids)];
}
close();

const body = Object.entries(out)
  .map(([k, ids]) => `  ${k}: [${ids.join(", ")}],`)
  .join("\n");
writeFileSync(
  new URL("../src/discover/keywords.ts", import.meta.url),
  `// TMDB keyword ids for the theme lists. Generated by scripts/resolve-keywords.mjs
// from TMDB's /search/keyword (exact names only, never typed from memory).
// Several ids per theme are combined with "|" (any of them).
export const KEYWORDS: Record<string, number[]> & {
${Object.keys(out).map((k) => `  ${k}: number[];`).join("\n")}
} = {
${body}
};
`,
);
console.log("wrote src/discover/keywords.ts");
